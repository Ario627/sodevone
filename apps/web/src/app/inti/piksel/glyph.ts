const CADANGAN = ['11111', '10001', '10001', '10001', '10001', '10001', '11111'];

export interface TitikPiksel {
  readonly teks: string;
  readonly kolom: number;
  readonly baris: number;
}

export function barisGlyph(karakter: string): readonly string[] {
  return PETA_GLYPH[karakter.toUpperCase()] ?? CADANGAN;
}

export function punyaGlyph(karakter: string): boolean {
  return karakter.toUpperCase() in PETA_GLYPH;
}

export function lebarTeks(teks: string): number {
  const jumlah = [...teks].length;
  return jumlah === 0 ? 0 : jumlah * LEBAR_GLYPH + (jumlah - 1) * JARAK_GLYPH;
}

export function titikTeks(teks: string): readonly TitikPiksel[] {
  const titik: TitikPiksel[] = [];
  let geser = 0;
  for (const karakter of teks) {
    if (karakter === ' ') {
      geser += LEBAR_GLYPH + JARAK_GLYPH;
      continue;
    }
    const baris = barisGlyph(karakter);
    for (let b = 0; b < TINGGI_GLYPH; b += 1) {
      const barisPiksel = baris[b] ?? '';
      for (let k = 0; k < LEBAR_GLYPH; k += 1) {
        if (barisPiksel[k] === '1') {
          titik.push({ teks: karakter, kolom: geser + k, baris: b });
        }
      }
    }
    geser += LEBAR_GLYPH + JARAK_GLYPH;
  }
  return titik;
}